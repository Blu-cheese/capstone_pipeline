"""
Post-sweep RQ3 tables, added Nov 6, 2026 for the RQ3_SPEC §6 wrap-up at
Adithya's request. make_tables.py is left exactly as it was at the sweep, so
its scoring code is unchanged since before any RQ3 run; these tables score
nothing.

  T12  Resolution (descriptive). For each condition x regime x seed: min and
       max of final 17-class test macro-F1 over replicates 0 to 2, and the
       spread (max - min).
  E1   EXPLORATORY, not preregistered. Buffer purity per class: of the replay
       memory rows selected for a class (by training label), how many have
       gold != training label. teacher_I, perm_I, rand_I; replay; r0; per
       seed. A class is marked thin (*) when it has fewer than 15 training
       rows in that condition and seed (the frozen threshold, used here as a
       marker only); a class with <= 10 rows puts all of them in memory.
  E2   EXPLORATORY, not preregistered. Per-class test F1 under joint at r0 for
       gold_I, teacher_I and rand_I (E2), and per seed the three classes where
       teacher_I and rand_I fall furthest below gold_I (E2b).

Saved run files only, no training. Self-checks (assertions): gold_I memory is
100% pure; every memory row carries its class's training label; memory sizes
at r0 are min(m, class rows); per-class F1 recomputed from saved predictions
reproduces each joint run's stored final macro-F1.

    venv/bin/python -m continual.rq3_extra --hash-rq3 504fb3e
"""

import argparse
import csv
from pathlib import Path
from typing import Dict, List

import numpy as np

from continual import config
from continual.make_tables import SEEDS, THRESH, select_rq3_runs
from continual.conditions import RQ3_REGIMES, RQ3_TRACKS
from continual.student import macro_f1

TABLE_DIR = config.RESULTS_DIR / "tables"
NOISY = ("teacher_I", "perm_I", "rand_I")
THIN = 15
EXPLORATORY = "EXPLORATORY, not preregistered (added after the sweep)."


def write(name: str, title: str, header: List[str], rows: List[List], notes: List[str],
          exploratory: bool = False) -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    md = [f"# {title}", "", "Generated by `continual/rq3_extra.py` from saved run files. "
          "Do not edit by hand.", ""]
    if exploratory:
        md += [f"**{EXPLORATORY}**", ""]
    md += [f"| {' | '.join(header)} |", f"|{'|'.join('---' for _ in header)}|"]
    md += [f"| {' | '.join(str(v) for v in row)} |" for row in rows]
    md += [""] + [f"- {n}" for n in notes]
    (TABLE_DIR / f"{name}.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    with open(TABLE_DIR / f"{name}.csv", "w", encoding="utf-8", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)


def short(name: str) -> str:
    return name.split(":", 1)[1]


# ---------------------------------------------------------------- T12

def table_T12(runs: Dict, reps: List[int]) -> None:
    rows, wide = [], 0
    for c in RQ3_TRACKS:
        for g in RQ3_REGIMES[c]:
            row = [c, g]
            for s in SEEDS:
                v = [runs[(c, g, s, r)].m["final_macro_f1_all"] for r in reps]
                spread = max(v) - min(v)
                wide += spread > THRESH
                row.append(f"{min(v):.3f} – {max(v):.3f} ({spread:.3f})")
            rows.append(row)
    n = len(rows) * len(SEEDS)
    write("T12_rq3_resolution", "T12 — resolution: final 17-class macro-F1 range over replicates",
          ["condition", "regime"] + [f"{s}: min – max (spread)" for s in SEEDS], rows,
          [f"Replicates r = {', '.join(map(str, reps))}: init seed = seed + 100r; rand_I, perm_I and "
           "gold_sub also redraw their labels or rows.",
           f"Spread above 0.03 (the real-difference threshold) in {wide} of {n} cells.",
           "Raw scores, unpaired. The PREREG rules compare paired differences within a replicate "
           "(T10), so a wide spread here does not by itself make a difference unreal.",
           "Descriptive, no scoring."])


# ---------------------------------------------------------------- E1

def buffer_purity(run, m: int) -> Dict[str, tuple]:
    """{class name: (impure memory rows, memory rows, class training rows, impure training rows)}."""
    P, mem = run.P, run.json("memory_indices.json")["classes"]
    label, gold, frow = P["train_label"], P["train_gold"], P["train_feature_row"]
    names = [str(x) for x in P["class_names"]]
    out = {}
    for name, entry in mem.items():
        k = entry["head_index"]
        assert names[k] == name
        rows = np.asarray(entry["train_rows"])
        assert np.array_equal(frow[rows], np.asarray(entry["feature_rows"])), name
        assert np.all(label[rows] == k), f"memory row without its class label: {name}"
        n_class = int((label == k).sum())
        assert len(rows) == min(m, n_class), (name, len(rows), n_class)
        out[name] = (int((gold[rows] != k).sum()), len(rows), n_class,
                     int((gold[label == k] != k).sum()))
    return out


def table_E1(runs: Dict) -> None:
    m = config.REPLAY_MEMORY_PER_RELATION
    for s in SEEDS:   # self-check: clean labels give a clean buffer
        pur = buffer_purity(runs[("gold_I", "replay", s, 0)], m)
        assert all(v[0] == 0 for v in pur.values()), f"gold_I memory impure on seed {s}"
    cols = [(c, s) for c in NOISY for s in SEEDS]
    data = {cs: buffer_purity(runs[(cs[0], "replay", cs[1], 0)], m) for cs in cols}
    classes = sorted(next(iter(data.values())))
    rows = []
    for name in classes:
        row = [short(name)]
        for cs in cols:
            bad, n, n_class, _ = data[cs][name]
            row.append(f"{bad}/{n}{'*' if n_class < THIN else ''}")
        rows.append(row)
    tot, exp = ["all classes, memory"], ["expected if memory were random within class"]
    for cs in cols:
        bad = sum(v[0] for v in data[cs].values())
        n = sum(v[1] for v in data[cs].values())
        e = sum(v[1] * v[3] / v[2] for v in data[cs].values())
        tot.append(f"{bad}/{n} ({bad / n:.2f})")
        exp.append(f"{e:.1f}/{n} ({e / n:.2f})")
    rows += [tot, exp]
    write("E1_rq3_buffer_purity",
          "E1 — replay buffer purity per class (memory rows whose training label ≠ gold), r0",
          ["class"] + [f"{c} {s}" for c, s in cols], rows,
          ["Cell = impure memory rows / memory rows for that class. Memory is selected per class "
           "by training label (k-means on the subject+object features, m = 10); r0 runs, which "
           "share memory with r1 and r2 for teacher_I (KMeans stays on the task-order seed) but "
           "not for perm_I and rand_I (their labels are redrawn).",
           f"* = fewer than {THIN} training rows with that label in that condition and seed "
           "(marker only); with 10 or fewer, the whole class is the memory.",
           "Last row: the impurity expected if each class's memory were drawn at random from that "
           "class's training rows (memory size × the class's training impurity, summed).",
           "Self-check: gold_I memory is 100% pure on every seed."], exploratory=True)


# ---------------------------------------------------------------- E2

def per_class_f1(run) -> Dict[str, float]:
    P = run.P
    names = [str(x) for x in P["class_names"]]
    pred = P["test_pred"][-1]
    mf, pc = macro_f1(P["test_gold"], pred, len(names))
    assert abs(mf - run.m["final_macro_f1_all"]) < 1e-6, (run.dir, mf)
    out = {names[k]: v for k, v in pc.items()}
    for name, v in run.m["per_class_f1"].items():
        assert abs(out[name] - v) < 6e-5, (run.dir, name)
    return out


def table_E2(runs: Dict) -> None:
    conds = ("gold_I", "teacher_I", "rand_I")
    F = {(c, s): per_class_f1(runs[(c, "joint", s, 0)]) for c in conds for s in SEEDS}
    classes = sorted(F[("gold_I", SEEDS[0])])
    rows = [[short(n)] + [f"{F[(c, s)][n]:.3f}" for s in SEEDS for c in conds] for n in classes]
    rows.append(["macro-F1"] + [f"{runs[(c, 'joint', s, 0)].m['final_macro_f1_all']:.3f}"
                                for s in SEEDS for c in conds])
    write("E2_rq3_per_class_f1", "E2 — per-class test F1 under joint, r0",
          ["class"] + [f"{s} {c}" for s in SEEDS for c in conds], rows,
          ["Final test F1 per class (1,144 gold test examples), joint regime, replicate 0.",
           "Recomputed from saved predictions; reproduces each run's stored macro-F1 and "
           "per-class F1."], exploratory=True)

    rows = []
    for s in SEEDS:
        for c in ("teacher_I", "rand_I"):
            drop = sorted(((F[(c, s)][n] - F[("gold_I", s)][n], n) for n in classes))[:3]
            rows.append([s, c] + [f"{short(n)} {d:+.3f}" for d, n in drop])
    write("E2b_rq3_largest_drops",
          "E2b — the three classes each condition hurts most relative to gold_I (joint, r0)",
          ["seed", "condition", "largest drop", "second", "third"], rows,
          ["Drop = F1(condition) − F1(gold_I) for the same class, seed and replicate 0."],
          exploratory=True)


def main():
    ap = argparse.ArgumentParser(description="Post-sweep RQ3 tables (T12, E1, E2)")
    ap.add_argument("--hash-rq3", default=None)
    args = ap.parse_args()
    runs, h, reps = select_rq3_runs(args.hash_rq3)
    if runs is None:
        raise SystemExit("rq3_extra: no RQ3 runs")
    table_T12(runs, reps)
    table_E1(runs)
    table_E2(runs)
    print(f"rq3_extra: T12, E1, E2, E2b from {len(runs)} runs at {h} -> {TABLE_DIR}")


if __name__ == "__main__":
    main()
